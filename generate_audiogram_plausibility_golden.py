"""Generates golden data for porting `audiogram_plausibility` elsewhere.

The audiograms below are synthetic, constructed for this file to exercise one
behaviour each. None is taken from a measured audiogram or a published dataset;
model_exact is computed from chosen model coefficients. The expected outputs
are computed once by the current module and written to a CSV, which
`audiogram_plausibility_test.py` checks the module against.

Regenerate only when the check is changed on purpose (for example a new
MAX_RMS_ERROR_DB), never just to make a failing test pass:
  python generate_audiogram_plausibility_golden.py
"""

import csv
from pathlib import Path

import numpy as np

import audiogram_plausibility as ap

OUTPUT_PATH = (Path(__file__).resolve().parent / 'tests' / 'golden_data'
               / 'audiogram_plausibility_cases.csv')
# Frequency columns of the CSV. A blank cell means not entered.
FREQS_HZ = (125, 250, 500, 750, 1000, 1500, 2000, 3000, 4000, 6000, 8000,
            10000)
STANDARD_HZ = (250, 500, 1000, 2000, 3000, 4000, 6000, 8000)
MODEL_COEFFS = (1.0, 0.3, -0.2, 0.1)


def _std(*dbhl: float) -> dict[int, float]:
  """An audiogram at the 8 standard frequencies, 250 Hz to 8 kHz."""
  return dict(zip(STANDARD_HZ, dbhl, strict=True))


def _model_audiogram() -> dict[int, float]:
  """The model at MODEL_COEFFS, rounded as written to the CSV."""
  dbhl = ap.basis_shapes(np.array(STANDARD_HZ, float)) @ MODEL_COEFFS
  return dict(zip(STANDARD_HZ, np.round(dbhl, 6).tolist(), strict=True))


# (case id, description, audiogram {Hz: dB HL}).
