def evaluate(audiogram: dict[int, float]) -> str:
  """Returns the outcome for an audiogram, as the module decides it."""
  try:
    return 'plausible' if ap.is_plausible(audiogram) else 'implausible'
  except ValueError:
    return 'error'


def in_range(audiogram: dict[int, float]) -> bool:
  """True if every threshold is within MIN_DBHL to MAX_DBHL."""
  return all(ap.MIN_DBHL <= v <= ap.MAX_DBHL for v in audiogram.values())


def header_lines() -> list[str]:
  return [
      'Golden data for audiogram_plausibility.',
      'Inputs (hl_<Hz>): synthetic audiograms, constructed for this file to '
      'exercise specific behaviour. None is taken from a measured audiogram '
      'or a published dataset; model_exact is computed from chosen model '
      'coefficients.',
      'Expected outputs (outcome onwards): computed from those inputs by '
      'generate_audiogram_plausibility_golden.py.',
      'Columns: hl_<Hz> are the entered thresholds (dB HL; blank = not '
      'entered). outcome is plausible, implausible, or error (invalid '
      'input: a frequency outside MIN_FREQUENCY_HZ to MAX_FREQUENCY_HZ, a '
      'required frequency missing, or too few frequencies). '
      'rms_error_db is the RMS error of the model fit, blank where no fit is '
      'made: for errors, and when a threshold is outside MIN_DBHL to '
      'MAX_DBHL (implausible without a fit).',
      'Compare rms_error_db to within 1e-4 dB.',
      f'MAX_RMS_ERROR_DB: {ap.MAX_RMS_ERROR_DB:g}',
      f'MIN_FREQUENCY_HZ: {ap.MIN_FREQUENCY_HZ:g}',
      f'MAX_FREQUENCY_HZ: {ap.MAX_FREQUENCY_HZ:g}',
      f'MIN_DBHL: {ap.MIN_DBHL:g}',
      f'MAX_DBHL: {ap.MAX_DBHL:g}',
      'REQUIRED_FREQUENCIES_HZ: '
      + ' '.join(str(f) for f in ap.REQUIRED_FREQUENCIES_HZ),
      f'MIN_FREQUENCIES: {ap.MIN_FREQUENCIES}',
  ]


def main():
  fieldnames = (['case_id', 'description']
                + [f'hl_{f}' for f in FREQS_HZ]
                + ['outcome', 'rms_error_db'])
  rows = []
  for case_id, description, audiogram in CASES:
    assert set(audiogram) <= set(FREQS_HZ), case_id
    outcome = evaluate(audiogram)
    row = {'case_id': case_id, 'description': description,
           'outcome': outcome}
    for f, v in audiogram.items():
      row[f'hl_{f}'] = f'{v:.6f}' if v != round(v) else f'{v:g}'
    if outcome != 'error' and in_range(audiogram):
      fit = ap.fit_global_model(audiogram)
      row['rms_error_db'] = f'{fit.rms_error_db:.6f}'
    rows.append(row)
  OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
  with open(OUTPUT_PATH, 'w', newline='', encoding='utf-8') as f:
    for line in header_lines():
      f.write(f'# {line}\n')
    writer = csv.DictWriter(f, fieldnames=fieldnames, lineterminator='\n')
    writer.writeheader()
    writer.writerows(rows)
  print(f'Wrote {len(rows)} cases to {OUTPUT_PATH}')
  for row in rows:
    print(f"  {row['case_id']:18} {row['outcome']:11} "
          f"{row.get('rms_error_db', '')}")


if __name__ == '__main__':
  main()
